import DoneAllOutlinedIcon from '@mui/icons-material/DoneAllOutlined';
import {
  Box,
  Button,
  Chip,
  Link as MuiLink,
  Pagination,
  Paper,
  Skeleton,
  Stack,
  ToggleButton,
  ToggleButtonGroup,
  Typography,
} from '@mui/material';
import { enqueueSnackbar } from 'notistack';
import { useState } from 'react';
import { Link } from 'react-router-dom';

import { EmptyState } from '@/components/feedback/EmptyState';
import { ErrorState } from '@/components/feedback/ErrorState';
import {
  useGetNotificationsQuery,
  useMarkAllNotificationsReadMutation,
  useMarkNotificationReadMutation,
} from '@/features/dashboard/api/dashboardApi';
import { DashboardPageHeader } from '@/features/dashboard/components/DashboardPageHeader';
import {
  formatDashboardDate,
  getNotificationTypeLabel,
  getSafeNotificationPath,
} from '@/features/dashboard/utils/dashboardFormatting';
import { useDocumentMetadata } from '@/hooks/useDocumentMetadata';

type ReadFilter = 'all' | 'unread' | 'read';
const PAGE_SIZE = 10;

export const NotificationsPage = () => {
  useDocumentMetadata(
    'Notifications | Career Portal',
    'Review and manage notifications for your candidate account.',
  );
  const [page, setPage] = useState(1);
  const [filter, setFilter] = useState<ReadFilter>('all');
  const { data, isError, isFetching, isLoading, refetch } = useGetNotificationsQuery({
    isRead: filter === 'all' ? undefined : filter === 'read',
    pageNumber: page,
    pageSize: PAGE_SIZE,
  });
  const [markRead, markReadState] = useMarkNotificationReadMutation();
  const [markAllRead, markAllState] = useMarkAllNotificationsReadMutation();

  const handleMarkRead = async (notificationId: string) => {
    try {
      await markRead(notificationId).unwrap();
    } catch {
      enqueueSnackbar('Unable to mark this notification as read.', { variant: 'error' });
    }
  };

  const handleMarkAllRead = async () => {
    try {
      await markAllRead().unwrap();
      enqueueSnackbar('All notifications marked as read.', { variant: 'success' });
    } catch {
      enqueueSnackbar('Unable to update notifications.', { variant: 'error' });
    }
  };

  return (
    <Stack spacing={4}>
      <DashboardPageHeader
        actions={
          <Button
            disabled={!data?.unreadCount || markAllState.isLoading}
            onClick={() => void handleMarkAllRead()}
            startIcon={<DoneAllOutlinedIcon />}
            variant="outlined"
          >
            Mark all read
          </Button>
        }
        description="Updates generated by jobs, applications, memberships, payments, and account security."
        eyebrow="Inbox"
        title="Notifications"
      />

      <ToggleButtonGroup
        aria-label="Filter notifications"
        exclusive
        onChange={(_, value: ReadFilter | null) => {
          if (!value) return;
          setFilter(value);
          setPage(1);
        }}
        size="small"
        value={filter}
      >
        <ToggleButton value="all">All</ToggleButton>
        <ToggleButton value="unread">Unread</ToggleButton>
        <ToggleButton value="read">Read</ToggleButton>
      </ToggleButtonGroup>

      {isFetching && data ? (
        <Typography aria-live="polite" color="text.secondary">
          Updating notifications…
        </Typography>
      ) : null}

      {isLoading && !data ? (
        <Stack aria-label="Loading notifications" role="status" spacing={2}>
          {Array.from({ length: 4 }, (_, index) => (
            <Skeleton key={index} height={128} variant="rounded" />
          ))}
        </Stack>
      ) : null}

      {isError && !data ? <ErrorState onRetry={() => void refetch()} /> : null}

      {data?.page.items.length === 0 ? (
        <EmptyState
          description={
            filter === 'all'
              ? 'Your account has no notifications yet.'
              : `There are no ${filter} notifications.`
          }
          title="Nothing to show"
        />
      ) : null}

      {data && data.page.items.length > 0 ? (
        <Stack spacing={2}>
          <Typography color="text.secondary">{data.unreadCount.toLocaleString()} unread</Typography>
          {data.page.items.map((notification) => {
            const actionPath = getSafeNotificationPath(notification.actionUrl);
            return (
              <Paper
                component="article"
                key={notification.id}
                sx={{
                  borderLeft: 4,
                  borderLeftColor: notification.isRead ? 'divider' : 'primary.main',
                  p: 3,
                }}
              >
                <Stack
                  alignItems={{ xs: 'flex-start', sm: 'center' }}
                  direction={{ xs: 'column', sm: 'row' }}
                  justifyContent="space-between"
                  spacing={2}
                >
                  <Box>
                    <Stack alignItems="center" direction="row" flexWrap="wrap" gap={1}>
                      <Typography component="h2" variant="h3">
                        {notification.title}
                      </Typography>
                      <Chip
                        label={getNotificationTypeLabel(notification.type)}
                        size="small"
                        variant="outlined"
                      />
                      {!notification.isRead ? (
                        <Chip color="primary" label="Unread" size="small" />
                      ) : null}
                    </Stack>
                    <Typography color="text.secondary" sx={{ mt: 1, whiteSpace: 'pre-line' }}>
                      {notification.message}
                    </Typography>
                    <Typography color="text.secondary" sx={{ mt: 1 }} variant="body2">
                      {formatDashboardDate(notification.createdAtUtc) ?? 'Date unavailable'}
                    </Typography>
                  </Box>
                  <Stack alignItems="flex-start" spacing={1}>
                    {actionPath ? (
                      <MuiLink component={Link} to={actionPath}>
                        Open update
                      </MuiLink>
                    ) : null}
                    {!notification.isRead ? (
                      <Button
                        disabled={markReadState.isLoading}
                        onClick={() => void handleMarkRead(notification.id)}
                        size="small"
                      >
                        Mark as read
                      </Button>
                    ) : null}
                  </Stack>
                </Stack>
              </Paper>
            );
          })}
          {data.page.totalPages > 1 ? (
            <Pagination
              aria-label="Notifications pagination"
              boundaryCount={1}
              color="primary"
              count={data.page.totalPages}
              onChange={(_, nextPage) => setPage(nextPage)}
              page={Math.min(page, data.page.totalPages)}
              showFirstButton
              showLastButton
              siblingCount={0}
              sx={{ alignSelf: 'center', pt: 1 }}
            />
          ) : null}
        </Stack>
      ) : null}
    </Stack>
  );
};
