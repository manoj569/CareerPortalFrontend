import { NotificationItem } from '@/features/dashboard/components/NotificationItem';
import { useNotificationActions } from '@/features/dashboard/hooks/useNotificationActions';
import { PageLoadingIndicator } from '@/components/feedback/PageLoadingIndicator';
import DoneAllOutlinedIcon from '@mui/icons-material/DoneAllOutlined';
import CheckCircleOutlineIcon from '@mui/icons-material/CheckCircleOutline';
import {
  Button,
  Pagination,
  Stack,
  ToggleButton,
  ToggleButtonGroup,
  Typography,
} from '@mui/material';
import { enqueueSnackbar } from 'notistack';
import { useRef, useState } from 'react';

import { EmptyState } from '@/components/feedback/EmptyState';
import { ErrorState } from '@/components/feedback/ErrorState';
import {
  useGetNotificationsQuery,
  useMarkAllNotificationsReadMutation,
} from '@/features/dashboard/api/dashboardApi';
import { DashboardPageHeader } from '@/features/dashboard/components/DashboardPageHeader';
import { useDocumentMetadata } from '@/hooks/useDocumentMetadata';
import { useAppSelector } from '@/hooks/reduxHooks';
import { selectIsAuthenticated } from '@/features/auth/store/authSlice';

type ReadFilter = 'all' | 'unread' | 'read';
const PAGE_SIZE = 10;

export const NotificationsPage = () => {
  const authenticated = useAppSelector(selectIsAuthenticated);
  useDocumentMetadata(
    'Notifications | Career Portal',
    'Review and manage notifications for your candidate account.',
  );
  const [page, setPage] = useState(1);
  const [filter, setFilter] = useState<ReadFilter>('all');
  const { data, isError, isFetching, isLoading, refetch } = useGetNotificationsQuery(
    {
      isRead: filter === 'all' ? undefined : filter === 'read',
      pageNumber: page,
      pageSize: PAGE_SIZE,
    },
    { skip: !authenticated, pollingInterval: authenticated ? 30000 : 0,
      skipPollingIfUnfocused: true, refetchOnMountOrArgChange: true },
  );
  const { act, busy, role } = useNotificationActions();
  const [markAllRead, markAllState] = useMarkAllNotificationsReadMutation();

  const markAllGuard = useRef(false);
  const handleMarkAllRead = async () => {
    if (!authenticated || busy || markAllGuard.current) return;
    markAllGuard.current = true;
    try {
      await markAllRead().unwrap();
      enqueueSnackbar('All notifications marked as read.', { variant: 'success' });
    } catch {
      enqueueSnackbar('Unable to update notifications. Please try again.', { variant: 'error' });
    } finally {
      markAllGuard.current = false;
    }
  };

  // Determine if all notifications are already read
  const areAllRead = data?.unreadCount === 0;
  if (!authenticated) return null;

  return (
    <Stack spacing={4}>
      <DashboardPageHeader
        actions={
          <Button
            // ✅ FIXED: Button is always clickable. We change the icon/text if all are already read.
            disabled={busy || markAllState.isLoading}
            onClick={() => void handleMarkAllRead()}
            startIcon={areAllRead ? <CheckCircleOutlineIcon /> : <DoneAllOutlinedIcon />}
            variant={areAllRead ? 'outlined' : 'outlined'}
            color={areAllRead ? 'success' : 'primary'}
          >
            {areAllRead ? 'All read' : markAllState.isLoading ? 'Marking...' : 'Mark all read'}
          </Button>
        }
        description="Updates generated by jobs, referrals, applications, memberships, payments, and account security."
        eyebrow="Inbox"
        title="Notifications"
      />

      <ToggleButtonGroup
        aria-label="Filter notifications"
        exclusive
        onChange={(_, value: ReadFilter | null) => {
          if (!value) return;
          setFilter(value);
          setPage(1);
        }}
        size="small"
        value={filter}
      >
        <ToggleButton value="all">All</ToggleButton>
        <ToggleButton value="unread">Unread</ToggleButton>
        <ToggleButton value="read">Read</ToggleButton>
      </ToggleButtonGroup>

      {isFetching && data ? (
        <Typography aria-live="polite" color="text.secondary">
          Updating notifications…
        </Typography>
      ) : null}

      {isLoading && !data ? <PageLoadingIndicator label="Loading notifications" /> : null}

      {isError && !data ? <ErrorState onRetry={() => void refetch()} /> : null}

      {data?.page.items.length === 0 ? (
        <EmptyState
          description={
            filter === 'all'
              ? 'Your account has no notifications yet.'
              : `There are no ${filter} notifications.`
          }
          title="Nothing to show"
        />
      ) : null}

      {data && data.page.items.length > 0 ? (
        <Stack spacing={2}>
          <Typography color="text.secondary">{data.unreadCount.toLocaleString()} unread</Typography>
          {data.page.items.map((notification) => (
            <NotificationItem
              key={notification.id}
              notification={notification}
              role={role}
              busy={busy || markAllState.isLoading}
              onAction={(item, open) => {
                void act(item, open);
              }}
            />
          ))}
          {data.page.totalPages > 1 ? (
            <Pagination
              aria-label="Notifications pagination"
              boundaryCount={1}
              color="primary"
              count={data.page.totalPages}
              onChange={(_, nextPage) => setPage(nextPage)}
              page={Math.min(page, data.page.totalPages)}
              showFirstButton
              showLastButton
              siblingCount={0}
              sx={{ alignSelf: 'center', pt: 1 }}
            />
          ) : null}
        </Stack>
      ) : null}
    </Stack>
  );
};
